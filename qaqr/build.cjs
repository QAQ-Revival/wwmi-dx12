const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');

function msbuild() {
  const vswhere = path.join(process.env['ProgramFiles(x86)'], 'Microsoft Visual Studio/Installer/vswhere.exe');
  const found = spawnSync(vswhere, ['-latest', '-products', '*', '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64', '-property', 'installationPath'], { encoding: 'utf8', windowsHide: true });
  const installation = found.stdout.split(/\r?\n/).find(Boolean);
  if (!installation) throw Error('Visual C++ x64 build tools are required');
  return path.join(installation, 'MSBuild/Current/Bin/amd64/MSBuild.exe');
}
function git(args) {
  const command = spawnSync('git', ['-c', 'credential.helper=', ...args], { cwd: root, windowsHide: true, encoding: 'utf8' });
  if (command.status) throw Error('Cannot identify the add-on source');
  return command.stdout.trim();
}
// What the project's WwmiBuildStamp task writes. Its inline C# needs the Roslyn component of Visual Studio,
// which a build with only the C++ tools does not have.
function writeBuildStamp(version) {
  const number = version.split('.').slice(0, 4).map(part => Number.parseInt(part, 10) || 0);
  while (number.length < 4) number.push(0);
  const digest = crypto.createHash('sha256');
  for (const file of ['rabbitfx/rfx_dxil.cpp', 'rabbitfx/rfx_dxil.h', 'rfx_glow_ir.inc', 'rabbitfx/pso_blend.h', 'rabbitfx/pso_blend.cpp']) digest.update(fs.readFileSync(path.join(root, 'reshade_addon', file)));
  const dirty = git(['status', '--porcelain', '--untracked-files=no']) ? '+dirty' : '';
  fs.writeFileSync(path.join(root, 'reshade_addon/build_stamp.h'), [
    '// GENERATED by qaqr/build.cjs -- do not edit, not tracked.', '#pragma once',
    `#define WWMI_VERSION "${version}"`, `#define WWMI_BUILD_SHA "${git(['rev-parse', '--short', 'HEAD'])}${dirty}"`,
    `#define WWMI_VERSION_NUM ${number.join(',')}`, `#define WWMI_RFX_SRC_HASH 0x${digest.digest('hex').slice(0, 8).toUpperCase()}u`, ''
  ].join('\r\n'));
}
// The files of a release, from the list package.proj keeps. The manager installs only the add-on and its folder.
function packageFiles(version) {
  const list = fs.readFileSync(path.join(root, 'package.proj'), 'utf8');
  return [...list.matchAll(/<WwmiPackageFile Include="\$\(WwmiRoot\)([^"]+)" To="([^"]+)" \/>/g)]
    .map(([, from, to]) => ({ from: path.join(root, from), to: to.replace('$(WwmiVersion)', version).replace(/\\/g, '/') }))
    .filter(({ to }) => to === 'wwmi_dx12.addon64' || to.startsWith('wwmi_dx12/'));
}
function build({ output = path.join(root, 'build_addon/component'), verifyOnly = false } = {}) {
  const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
  writeBuildStamp(version);
  const result = spawnSync(msbuild(), ['wwmi-dx12.sln', '/t:Build', '-m', '-nologo', '-v:minimal', '/p:Configuration=Release', '/p:Platform=x64', '/p:WwmiRT=0', '/p:WwmiDeploy=false', '/p:WwmiStampWritten=true'], { cwd: root, stdio: 'inherit', windowsHide: true });
  if (result.error || result.status) throw result.error || Error('The add-on build failed');
  if (verifyOnly) return;
  if (git(['status', '--porcelain', '--ignore-submodules=all'])) throw Error('Commit the reviewed add-on source before packaging');
  output = path.resolve(output);
  fs.rmSync(output, { recursive: true, force: true });
  const files = {};
  for (const { from, to } of packageFiles(version)) {
    const target = path.join(output, to);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(from, target);
    files[to] = crypto.createHash('sha256').update(fs.readFileSync(target)).digest('hex');
  }
  const changes = JSON.parse(fs.readFileSync(path.join(__dirname, 'changes.json'), 'utf8'));
  fs.writeFileSync(path.join(output, 'component.json'), JSON.stringify({
    source: 'https://github.com/QAQ-Revival/wwmi-dx12', sourceCommit: git(['rev-parse', 'HEAD']), version, upstream: changes.upstream,
    validation: changes.validation, gameRuntimeValidated: false, files
  }, null, 2));
  return output;
}
if (require.main === module) build({ verifyOnly: process.argv.includes('--verify-only') });
module.exports = { build };
